const {chromium}=require('playwright'),assert=require('node:assert/strict'),fs=require('node:fs');
const index=fs.readFileSync('index.html','utf8');
const css=fs.readFileSync('workspace-fullscreen.css','utf8');
const js=fs.readFileSync('workspace-fullscreen.js','utf8');
const appStart=index.indexOf('<div id="app" class="app hidden">');
const pageStart=index.indexOf('<section id="page-home"',appStart);
assert(appStart>0&&pageStart>appStart,'Actual app shell found');
const shell=index.slice(appStart,pageStart).replace('class="app hidden"','class="app"');
const localCss=[...index.matchAll(/<style(?:\s[^>]*)?>([\s\S]*?)<\/style>/gi)].map(m=>m[1]).join('\n');
assert(index.includes('workspace-fullscreen.css?v=1'));
assert(index.includes('workspace-fullscreen.js?v=1'));
assert.equal((index.match(/id="workspaceFullscreenToggle"/g)||[]).length,1);
const html='<!doctype html><html><head><meta name="viewport" content="width=device-width, initial-scale=1"><style>'+localCss+'\n'+css+'</style></head><body>'+shell+'<section class="page active" id="page-home"><div class="content"><h1 id="testHeading">Workspace content</h1><input id="testDraft" value="Keep me" /></div></section></main></div></body></html>';
(async()=>{const browser=await chromium.launch({headless:true,args:['--no-sandbox']});try{
 for(const viewport of [{width:1850,height:950},{width:1440,height:900},{width:1024,height:768},{width:768,height:1024},{width:390,height:844}]){
  const page=await browser.newPage({viewport});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.setContent(html,{waitUntil:'domcontentloaded'});
  await page.addScriptTag({content:js});
  const toggle=page.locator('#workspaceFullscreenToggle');
  assert.equal(await toggle.count(),1);
  assert.equal(await toggle.isVisible(),true);
  assert.equal(await toggle.getAttribute('aria-pressed'),'false');
  const menu=page.locator('#sidebar'),main=page.locator('#app > .main');
  const before=await main.boundingBox();
  if(viewport.width>850)assert(before.x>180,'Desktop starts with sidebar offset');
  await page.locator('#testDraft').fill('Preserve student work');
  await toggle.click();
  assert.equal(await toggle.getAttribute('aria-pressed'),'true');
  assert.equal(await menu.isHidden(),true,'Whole vertical sidebar hidden');
  assert.equal(await page.locator('#app').evaluate(e=>e.classList.contains('compass-focus-mode')),true);
  const debug=await page.evaluate(()=>{let app=document.querySelector('#app'),main=document.querySelector('#app>.main');return{appClass:app.className,mainParent:main?.parentElement?.id,mainMargin:getComputedStyle(main).marginLeft,mainRect:main?.getBoundingClientRect().toJSON(),sidebar:getComputedStyle(document.querySelector('#sidebar')).display,appRect:app.getBoundingClientRect().toJSON(),bodyWidth:document.body.scrollWidth,viewport:window.innerWidth}});console.log('DEBUG EXPANDED',viewport.width,JSON.stringify(debug));
  const expanded=await main.boundingBox();
  assert(Math.abs(expanded.x)<1,'Main workspace starts at screen left: '+expanded.x);
  assert(expanded.width>=viewport.width-2,'Main workspace expands full width');
  assert.equal(await page.locator('#testHeading').innerText(),'Workspace content','Page retained');
  assert.equal(await page.locator('#testDraft').inputValue(),'Preserve student work','Unsaved form remains intact');
  assert.equal(await page.locator('#mobileMenu').isHidden(),true);
  assert.equal((await toggle.innerText()).includes('Show Menu'),viewport.width>540);
  const rect=await toggle.boundingBox();
  assert(rect.x+rect.width<=viewport.width+1,'Right corner inside screen');
  assert(viewport.width-(rect.x+rect.width)<=18,'Toggle stays at far right corner');
  await toggle.click();
  assert.equal(await toggle.getAttribute('aria-pressed'),'false');
  assert.equal(await menu.isHidden(),false,'Vertical navigation restored');
  assert(Math.abs((await main.boundingBox()).x-before.x)<1,'Original main margin restored');
  assert.equal(await page.locator('#testDraft').inputValue(),'Preserve student work');
  await toggle.focus();await page.keyboard.press('Enter');
  assert.equal(await toggle.getAttribute('aria-pressed'),'true','Accessible keyboard toggle');
  await page.keyboard.press('Space');
  assert.equal(await toggle.getAttribute('aria-pressed'),'false','Accessible keyboard restore');
  await page.emulateMedia({media:'print'});
  assert.equal(await toggle.isHidden(),true,'Toggle not printed');
  await page.emulateMedia({media:'screen'});
  assert.equal(errors.length,0,errors.join(';'));
  console.log('PASS fullscreen sidebar toggle',viewport.width,'hide/expand/restore, keyboard, preserved forms, print');
  await page.close();
 }
}finally{await browser.close()}})().catch(e=>{console.error(e);process.exit(1)});
